def _load_kr_portals():
    """The KR-derived `portals.json`, malformed rows dropped (world-portal-guards): 13 key a
    `None` or empty index (`None_None`, `_`, `1002_None`) and the rest carry a null
    destination. Only the last-resort fallback now: 237 of the 594 EN portals are missing
    from it and 132 of its arrivals disagree with the EN layout (world doc B14)."""
    try:
        with open(PORTALS_PATH, encoding='utf-8') as f:
            raw = json.load(f)
    except (OSError, ValueError) as e:
        log.warning(f'[CONTENT] {PORTALS_PATH}: {e}; no portals (every 0x7E is ignored)')
        raw = {}
    table, dropped = {}, []
    for key, row in raw.items():
        if _PORTAL_KEY.fullmatch(str(key)) and isinstance(row, list) and len(row) >= 3                 and all(v is not None for v in row[:3]):
            table[key] = row
        else:
            dropped.append(key)
    if dropped:
        log.info(f'[CONTENT] {len(table)} portals from {PORTALS_PATH}; '
                 f'{len(dropped)} malformed key(s) dropped: {sorted(dropped)}')
    return table


def _rows_to_table(rows):
    return {key: [int(r['dest']), float(r['x']), float(r['y'])] for key, r in rows.items()
            if _PORTAL_KEY.fullmatch(str(key)) and r.get('dest')}


def portals():
    """The portal table as `{"<map>_<collision line index>": [next_map, x, y]}`.

    world-portal-table-en: the EN client's own map files are the source. In order:
      1. `server/portals_en.json`, generated by `python en_maps.py` from every EN
         `hs/stageAA_BB.hmi` + `.hsi` line list (593 portals, the 101_23 -> 102 live
         anchor asserted at generation);
      2. the same table built in memory from the installed client files, when the JSON is
         missing (a copied server that has the client but not the generated file);
      3. the KR `portals.json`, only when neither exists, so a bare server still starts.
    `portals_source()` says which one is live; the portal log names it on a miss."""
    global _portals, _portals_source
    with _lock:
        if _portals is not None:
            return _portals
        table, source = None, None
        path = portals_en_path()            # per client build (client-2009-world)
        try:
            with open(path, encoding='utf-8') as f:
                table = _rows_to_table(json.load(f).get('portals', {}))
            source = path
        except (OSError, ValueError, AttributeError, TypeError, KeyError) as e:
            log.warning(f'[CONTENT] {path}: {e}; building the EN portal table '
                        f'from the client map files')
            import en_maps              # late: en_maps imports this module
            rows, report = en_maps.build_portal_table()
            if rows:
                table, source = _rows_to_table(rows), f'{client_dir()}/hs/*.hmi (in memory)'
                bad = en_maps.check_live_portals(rows)
                if bad:
                    log.error(f'[CONTENT] EN portal table contradicts the live captures: {bad}')
        if not table:
            table, source = _load_kr_portals(), f'{PORTALS_PATH} (KR fallback)'
            log.warning(f'[CONTENT] no EN portal table: using the KR {PORTALS_PATH} '
                        f'({len(table)} rows; 237 EN portals missing from it)')
        else:
            log.info(f'[CONTENT] {len(table)} EN portals from {source}')
        _portals, _portals_source = table, source
        return _portals


def portals_source():
    portals()
    return _portals_source


_portal_lines = None


def portal_line(map_code, portal_code):
    """The collision line [x_start, y, x_end] of a portal (the generated table's `line`), or
    None. The flea-market return uses it (world-flea-return): the market's single exit tile
    (stage97_01 Layer 53, value_num 101) names map 101 whatever town the player came from,
    so the server stands him back on the town's own market portal instead."""
    global _portal_lines
    with _lock:
        if _portal_lines is None:
            lines = {}
            try:
                with open(portals_en_path(), encoding='utf-8') as f:
                    for key, row in (json.load(f).get('portals') or {}).items():
                        line = row.get('line') if isinstance(row, dict) else None
                        if line and len(line) == 3:
                            lines[key] = [float(v) for v in line]
            except (OSError, ValueError, AttributeError, TypeError):
                pass
            _portal_lines = lines
        return _portal_lines.get(f'{int(map_code)}_{int(portal_code)}')


def portal(map_code, portal_code):
    """(next_map, x, y) for a portal on `map_code`, or None when it is not mapped. The
    caller must do nothing on None: re-loading the same map duplicates the player entity
    (world-portal-guards)."""
    row = portals().get(f'{int(map_code)}_{int(portal_code)}')
    if not row or len(row) < 3:
        return None
    return int(row[0]), float(row[1]), float(row[2])


def map_file(map_code):
    """The client's own map file for a map code: sprintf './hs/stage%02u_%02u.hmi'
    (map_code/100, map_code%100) at 0x0044EB68, which is what S2C 0x03/0x08 make it load."""
    map_code = int(map_code)
    return hs_path(f'stage{map_code // 100:02d}_{map_code % 100:02d}.hmi')


def map_destinations(map_code):
    """The destination map codes of every portal tile on `map_code`, read from the EN map
    file itself: `<Tile ... event="1" value_num="<dest>"/>` (world_movement_npc.md 1.5).

    Only the destinations, not the indexes (the line indexes are en_maps.py's portal table).
    This answers "which maps does this map actually lead to", which is what an unknown
    portal key is logged with (world-portal-guards). Empty when the client files are not
    installed - it is a log aid, never a gate."""
    map_code = int(map_code)
    with _lock:
        cached = _map_dests.get(map_code)
        if cached is not None:
            return cached
    try:
        text = decode_hs_text(map_file(map_code))
    except (OSError, ContentError) as e:
        log.debug(f'[CONTENT] map {map_code}: {e}; no EN portal destinations')
        text = ''
    dests = []
    for tile in _PORTAL_TILE.finditer(text):
        dest = int(tile.group(1))
        if dest and dest not in dests:
            dests.append(dest)
    with _lock:
        _map_dests[map_code] = dests
    return dests
