class QuestDef:
    """One hqi quest line. Everything is decimal (FUN_00409FE0 `%04d` / `%03d`)."""
    __slots__ = ('idx', 'title_text', 'send', 'reward', 'demand', 'job', 'exp', 'money',
                 'start_lev', 'end_lev', 'repeat', 'explain', 'reqpro', 'npc', 'prev_q',
                 'next_q', 'snpc', 'enpc', 'dialogs', 'intro', 'completed_text', 'indun_map')

    def __init__(self, idx, title_text, fields):
        f = fields
        self.idx = idx
        self.title_text = title_text
        self.send = _pairs(_digit_groups(f.get('Send', []), QUEST_SEND_SLOTS, 4),
                           _digit_groups(f.get('Send_Num', []), QUEST_SEND_SLOTS, 3))
        self.reward = _pairs(_digit_groups(f.get('Reward', []), QUEST_REWARD_SLOTS, 4),
                             _digit_groups(f.get('Reward_Num', []), QUEST_REWARD_SLOTS, 3))
        self.demand = _pairs(_digit_groups(f.get('Demand', []), QUEST_DEMAND_SLOTS, 4),
                             _digit_groups(f.get('Demand_Num', []), QUEST_DEMAND_SLOTS, 3))
        self.job = (f.get('Job') or [''])[0]                 # 21 flag chars
        self.exp = _int(f.get('Exp'))
        self.money = _int(f.get('Money'))                    # signed: < 0 is a fee
        self.start_lev = _int(f.get('Start_Lev'))
        self.end_lev = _int(f.get('End_Lev'))
        self.repeat = _int(f.get('Repeat'))
        self.explain = _int(f.get('Explain'))
        self.reqpro = _int(f.get('ReqPro'))                  # kill count
        self.npc = _int(f.get('NPC'))                        # npccode to kill (E5)
        self.prev_q = _int(f.get('PrevQuest'))
        self.next_q = _int(f.get('NextQuest'))
        self.snpc = _int(f.get('SNPC'))                      # offering NPC (0 = never offered)
        self.enpc = _int(f.get('ENPC'))                      # turn-in NPC
        self.intro = _int(f.get('Intro'))
        self.completed_text = _int(f.get('Completed'))
        self.dialogs = (_int(f.get('First')), _int(f.get('Ing')),
                        _int(f.get('Finish')), _int(f.get('None')))
        self.indun_map = (f.get('IndunMapName') or ['None'])[0]

    @property
    def needs_slot(self):
        """False for the 9 talk-only quests: the client files those straight into the
        completed list and uses no active slot (quest_cards_misc 1.3, Q-B3)."""
        return self.money < 0 or bool(self.demand) or self.reqpro != 0

    def job_allows(self, class_id, tier=0):
        """The hqi Job string indexed `class + 7 * tier` (quest_cards_misc E1). An absent or
        short string allows everyone, which is how the client reads a missing flag."""
        index = int(class_id) + JOB_CLASSES * int(tier)
        if not self.job or not 0 <= index < len(self.job):
            return True
        return self.job[index] == '1'

    def __repr__(self):
        return (f'<QuestDef {self.idx} send={self.send} demand={self.demand} '
                f'reward={self.reward} exp={self.exp} money={self.money} reqpro={self.reqpro}>')


class QuestCatalog:
    def __init__(self, defs, source):
        self.defs = defs
        self.source = source

    @classmethod
    def load(cls, path):
        text = decode_hs_text(path)
        defs = {}
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith('Number_of_'):
                continue
            head, fields = _split_record(line, 2)
            try:
                idx = int(head[0], 10)
                title = int(head[1], 10)
            except (IndexError, ValueError):
                continue
            defs[idx] = QuestDef(idx, title, fields)
        if not defs:
            raise ContentError(f'{path}: no quest records')
        return cls(defs, path)

    def get(self, quest_id):
        try:
            return self.defs.get(int(quest_id))
        except (TypeError, ValueError):
            return None

    def exists(self, quest_id):
        return self.get(quest_id) is not None

    def offered_by(self, snpc):
        return [q for q in self.defs.values() if q.snpc == snpc]

    def kill_quests(self, npccode):
        """Quests whose ReqPro counter this monster feeds (kill-progress, F3)."""
        return [q for q in self.defs.values() if q.reqpro and q.npc == npccode]

    def __len__(self):
        return len(self.defs)

    def __contains__(self, quest_id):
        return self.exists(quest_id)


