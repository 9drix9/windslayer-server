def configure(client_dir=None, client_build=None):
    """Point the loader at a client install (config CLIENT_DIR / CLIENT_DIR_2009) of a client
    build ('2008' default, '2009'; config CLIENT_BUILD). The caches are dropped only when the
    directory or the build actually changes: every GameServer construction calls this
    (offline tests build one per test), and re-reading the 2 MB item table each time both
    costs a fifth of a second and lets one thread's reload stall another thread's lookup.

    The build picks the tables that are NOT inside the client files (client-2009-world):
    the generated portal table (portals_en_path), the item-name source (item_name) and the
    item Kind -> equip slot switch (ItemCatalog.client_build, inventory.kind_tables). None
    keeps the current build (a directory-only call, e.g. en_maps.py --client-dir)."""
    global _client_dir, _client_build
    with _lock:
        resolved = _client_dir
        if client_dir:
            resolved = os.path.abspath(os.path.join(HERE, os.path.expanduser(client_dir)))
        build = _client_build if client_build is None else str(client_build)
        if build not in PORTALS_EN_PATHS:
            raise ContentError(f'client build must be one of {sorted(PORTALS_EN_PATHS)}, not {client_build!r}')
        if resolved != _client_dir or build != _client_build:
            _client_dir, _client_build = resolved, build
            reload()
        return _client_dir


