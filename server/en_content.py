def reload():
    """Drop every cache (GM sub 0x00 `/update`, tests). The next accessor re-reads the files."""
    global _items, _quests, _cards, _names, _portals, _portals_source, _npcs, _gamedef_conn
    global _portal_lines
    with _lock:
        _items = _quests = _cards = _names = _portals = _npcs = _portals_source = None
        _portal_lines = None
        _gamedef_cache.clear()
        _map_dests.clear()
        _spawns.clear()
        _gather.clear()
        _lng.clear()
        import en_maps                  # late: en_maps imports this module
        en_maps.clear_cache()
        if _gamedef_conn is not None:
            try:
                _gamedef_conn.close()
            except sqlite3.Error:
                pass
            _gamedef_conn = None


