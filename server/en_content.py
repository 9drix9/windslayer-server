class CardCatalog:
    """Monster cards: hii Type 2 records with CardSpr != 0 (64 in EN). `card_npc` is the
    monster npccode the card belongs to (quest_cards_misc 3.1)."""

    def __init__(self, defs):
        self.defs = defs

    @classmethod
    def from_items(cls, catalog):
        return cls({i: d for i, d in catalog.defs.items()
                    if d.type == TYPE_ETC and d.card_spr})

    def get(self, item_id):
        try:
            return self.defs.get(int(item_id))
        except (TypeError, ValueError):
            return None

    def exists(self, item_id):
        return self.get(item_id) is not None

    def for_npc(self, npccode):
        """The card ids that belong to this monster npccode (card EXP bonus, Q2)."""
        return [i for i, d in self.defs.items() if d.card_npc == npccode]

    def __len__(self):
        return len(self.defs)


