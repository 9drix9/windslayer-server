def gather_nodes(map_code):
    """{hni idx} of the gather nodes placed on `map_code` (the per-map content table of
    item_inventory F13 step 2; Q10 answered from the client's own files).

    A node is a type 1/2 template on one of the map's event-2 tiles. The client builds those
    entities itself (FUN_00444100 keeps every type <= 2 tile, like the town NPCs: no server
    spawn), and each one carries its template's 1-based position in the hni list at entity
    +0xE60 - the `gather_node_record_index` C2S 0x69 sends (spec 0x4685B2/0x69; the gather
    start FUN_00467b00 (2009 FUN_00471960) looks the same index up with RosterLookupByIndex
    and reads +0x644 type / +0x640 grade from it). So the index is NpcCatalog.at_index(),
    and this table only answers "is such a node on this map". Both EN builds place them on
    the herbal farms (x41/x42: 241, 242, 441, ...) and mining areas (x43/x44); 2009 adds
    1501/1502/1601/1602."""
    import en_maps                      # late: en_maps imports this module
    map_code = int(map_code)
    with _lock:
        cached = _gather.get(map_code)
        if cached is not None:
            return cached
    data = en_maps.load_map(map_code)
    catalog = npcs()
    out = set()
    for tile in (data.npc_tiles() if data is not None else []):
        tpl = catalog.get(tile.npc_id)
        if tpl is not None and tpl.type in GATHER_NODE_TYPES:
            out.add(tpl.idx)
    out = frozenset(out)
    with _lock:
        _gather[map_code] = out
    return out


