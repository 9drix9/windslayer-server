class ItemDef:
    """One hii record. Attribute names follow the design doc's column mapping
    (item_inventory.md 1.1), not the client's offsets."""
    __slots__ = ('id', 'title_text', 'type', 'sprite', 'hp', 'mp', 'job', 'job2', 'kind',
                 'spr_num', 'gender', 'con', 'skill_lv', 'text', 'lv', 'buy', 'sell',
                 'pmoney', 'ct', 'card_spr', 'card_npc', 'cash', 'cash_cls', 'cash_t',
                 'cash_p', 'cash_v', 'cash_b', 'cash_st', 'union_ids', 'union_counts', 'union_kind',
                 'w_att', 'defense', 's_att', 'stat_str', 'stat_dex', 'stat_int', 'stat_tol', 'mhp', 'mmp',
                 'attribute', 'attri_atk', 'attri_def', 'skill_p_a', 'skill_p_d',
                 'skill_a_a', 'skill_a_d')

    def __init__(self, item_id, fields):
        f = fields
        self.id = item_id
        self.title_text = _int(f.get('Title'))
        self.type = _int(f.get('Type'))
        self.sprite = _int(f.get('Sprite'))
        self.hp = _int(f.get('HP'))
        self.mp = _int(f.get('MP'))
        self.job = _ints(f.get('Job', []))                  # 7 class flags, job[0] = any
        self.job2 = _ints(f.get('Job2', []))
        self.kind = _int(f.get('Kind'), -1)                 # def+0x1CC, equipment only
        self.spr_num = _int(f.get('Spr_Num'))               # worn body sprite
        self.gender = _int(f.get('Gender'))
        self.con = _int(f.get('Con'))                       # def+0x1C8 buff duration (proven live)
        self.skill_lv = _int(f.get('Skill_Lv'))
        self.text = _int(f.get('Text'))
        self.lv = _int(f.get('Lv'))
        self.buy = _int(f.get('Buy'))
        self.sell = _int(f.get('Sell'))
        self.pmoney = _int(f.get('PMoney'))                 # Victy price
        self.ct = _int(f.get('CT'))                         # cooldown ms
        self.card_spr = _int(f.get('CardSpr'))
        self.card_npc = _int(f.get('CardNpc'))
        self.cash = _int(f.get('Cash'))                     # def+0x1F0: no sell/drop/trade
        self.cash_cls = _int(f.get('Cash_Cls'))
        self.cash_t = _int(f.get('Cash_T'))
        self.cash_p = _int(f.get('Cash_P'))                 # def+0x1FC Item Mall price (Wind Cash)
        # premium_cash-catalog (P8): the rest of the mall columns the hii carries (cash.py).
        self.cash_v = _int(f.get('Cash_V'))                 # count (Cash_T 1) or days (Cash_T 2)
        self.cash_b = _int(f.get('Cash_B'))                 # shop badge 0..5
        self.cash_st = _int(f.get('Cash_ST'))               # 0 / 1 / 2 / 5, meaning unknown
        self.union_ids = _digit_groups(f.get('Union', []), 8, 4)
        self.union_counts = _digit_groups(f.get('Union_Cnt', []), 8, 4)
        self.union_kind = _int(f.get('Union_Kind'))
        self.w_att = _int(f.get('W_Att'))
        self.defense = _int(f.get('Def'))
        self.s_att = _int(f.get('S_Att'))
        self.stat_str = _int(f.get('Str'))
        self.stat_dex = _int(f.get('Dex'))
        self.stat_int = _int(f.get('Int'))
        self.stat_tol = _int(f.get('Tol'))
        self.mhp = _int(f.get('mHP'))                       # def+0x160: max HP while slotted
        self.mmp = _int(f.get('mMP'))                       # def+0x164
        # Skill / option columns (combat_skill.md 1.1, cs-skill-defs). `attribute` is def+0x190:
        # the element of an attack skill, and for an option stone worn in an equipment block
        # the kind of bonus FUN_0041ACE0 applies (1 max-HP, 2 max-MP, 3 HP regen, 4 MP regen).
        self.attribute = _int(f.get('Attribute'))
        self.attri_atk = _int(f.get('Attri_Atk'))           # def+0x1A0
        self.attri_def = _int(f.get('Attri_Def'))           # def+0x1A4
        self.skill_p_a = _int(f.get('Skill_P_A'))           # def+0x1B8..+0x1C4: stat modifiers
        self.skill_p_d = _int(f.get('Skill_P_D'))           # while a buff slot is active
        self.skill_a_a = _int(f.get('Skill_A_A'))
        self.skill_a_d = _int(f.get('Skill_A_D'))

    @property
    def tab(self):
        return TAB_BY_TYPE.get(self.type)

    @property
    def is_cash(self):
        """def+0x1F0 != 0: the client refuses to sell, drop, deposit or trade it."""
        return self.cash != 0

    @property
    def recipe(self):
        """[(material id, count)] of the Union columns (crafting, item_inventory F11)."""
        return _pairs(self.union_ids, self.union_counts)

    @property
    def name(self):
        return item_name(self.id)

    def __repr__(self):
        return f'<ItemDef {self.id} {self.name!r} type={self.type} kind={self.kind}>'


class ItemCatalog:
    """The EN item table. `exists` is the single id gate every grant, drop, shop and quest
    path goes through (S2-11: the client silently ignores an id past its table)."""

    def __init__(self, defs, source, max_id=EN_ITEM_MAX_ID, client_build=None):
        self.defs = defs
        self.source = source
        # The table size of THIS catalog: 4248 in the 2008 hii, 4322 in the 2009 one
        # (client-2009-world). The client's own lookup returns NULL past its table.
        self.max_id = max_id
        # The client build whose files these are (items() sets it). Rules keyed by the
        # item's own columns - the Kind -> equip slot switch (inventory.kind_tables) - follow
        # it, so a record never meets the other build's table.
        self.client_build = client_build

    @classmethod
    def load(cls, path):
        text = decode_hs_text(path)
        defs = {}
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith('Number_of_'):
                continue
            head, fields = _split_record(line, 1)
            try:
                item_id = int(head[0], 10)
            except (IndexError, ValueError):
                continue
            defs[item_id] = ItemDef(item_id, fields)
        if not defs:
            raise ContentError(f'{path}: no item records')
        return cls(defs, path, max(defs))

    @classmethod
    def from_dump(cls, path):
        """Fallback: the live client dump (`en_item_catalog.json`), which carries only the
        id, EN name and Type. Enough for the id gate and the 0x15 Type routing; every
        numeric rule (price, Kind, cooldown) is missing, so callers see kind -1 / buy 0."""
        with open(path, encoding='utf-8') as f:
            raw = json.load(f)
        defs = {int(k): ItemDef(int(k), {'Type': [str(v.get('type', 0))]}) for k, v in raw.items()}
        return cls(defs, path, max(defs) if defs else EN_ITEM_MAX_ID)

    def get(self, item_id):
        try:
            return self.defs.get(int(item_id))
        except (TypeError, ValueError):
            return None

    def exists(self, item_id):
        """True when the EN client has a definition for this id. Anything else (0, a KR-only
        id above 4248, a non-number) never changes server state and never goes on the wire."""
        if isinstance(item_id, bool):          # True is not item 1
            return False
        try:
            item_id = int(item_id)
        except (TypeError, ValueError):
            return False
        if not 1 <= item_id <= self.max_id:
            return False
        return item_id in self.defs

    def type_of(self, item_id):
        """Client item Type (0 stack, 1 equipment, 2 etc, 3 skill book, 4 class change,
        5 cash), or None for an id the EN client does not have."""
        d = self.get(item_id)
        return None if d is None else d.type

    def tab_of(self, item_id):
        """Bag tab name ('consume' / 'equip' / 'etc' / 'cash') or None for a type the client
        consumes on receipt (skill book, class change) or an unknown id."""
        d = self.get(item_id)
        return None if d is None else d.tab

    def kind_of(self, item_id):
        d = self.get(item_id)
        return None if d is None or d.kind < 0 else d.kind

    def price(self, item_id, qty=1, victy=False):
        """u64 cost of `qty` of this item (shop_storage 1.3: compute in u64, never trust the
        client's 32-bit check)."""
        d = self.get(item_id)
        if d is None:
            return 0
        return max(0, int(d.pmoney if victy else d.buy)) * max(0, int(qty))

    def ids_of_type(self, item_type):
        return [i for i, d in self.defs.items() if d.type == item_type]

    def filter_ids(self, ids):
        """The ids of `ids` the EN client actually has (drop tables, shop lists, rewards)."""
        return [i for i in ids if self.exists(i)]

    def __len__(self):
        return len(self.defs)

    def __contains__(self, item_id):
        return self.exists(item_id)


