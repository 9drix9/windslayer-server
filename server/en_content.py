# ------------------------------------------------------------- asset cipher ---
def decode_hs(path):
    """Plain bytes of one `hs/` asset file: undo the additive cipher and drop the SHA-1
    footer. Raises OSError when the file is missing (callers decide the fallback)."""
    with open(path, 'rb') as f:
        raw = f.read()
    if len(raw) <= HS_FOOTER_BYTES:
        raise ContentError(f'{path}: {len(raw)} B is not a packed hs file')
    body = raw[:-HS_FOOTER_BYTES]
    return bytes((b + HS_ADD[i % 3]) & 0xFF for i, b in enumerate(body))


def decode_hs_text(path):
    """`decode_hs` as text. The tables hold ASCII numbers plus cp949 strings (the client's
    codepage), so a stray byte never aborts the load."""
    return decode_hs(path).decode('cp949', 'replace')


def _split_record(line, positional):
    """(leading tokens, {key: [value tokens]}) for one `<id> [<title>] Key: v ...` line."""
    tokens = line.split()
    fields, key = {}, None
    for token in tokens[positional:]:
        if len(token) > 1 and token.endswith(':'):
            key = token[:-1]
            fields[key] = []
        elif key is not None:
            fields[key].append(token)
    return tokens[:positional], fields


def _int(tokens, default=0):
    """First token of a field as an int (the hs files write plain decimal)."""
    if not tokens:
        return default
    try:
        return int(tokens[0], 10)
    except ValueError:
        return default


def _ints(tokens):
    out = []
    for t in tokens:
        try:
            out.append(int(t, 10))
        except ValueError:
            out.append(0)
    return out


def _digit_groups(tokens, count, width):
    """`count` fixed-width decimal fields of one packed string ("0179000..." -> [179, 0, ...]).
    A short or missing string pads with zeros instead of raising: the loader must not lose
    291 quests over one malformed line."""
    text = tokens[0] if tokens else ''
    out = []
    for i in range(count):
        chunk = text[i * width:(i + 1) * width]
        try:
            out.append(int(chunk, 10))
        except ValueError:
            out.append(0)
    return out


def _pairs(ids, counts):
    """[(id, count)] for the non-zero id slots, with a missing count read as 1 (the client
    grants at least one; Send_Num 000 with a real id does not occur in the EN tables)."""
    return [(i, counts[n] if n < len(counts) and counts[n] else 1)
            for n, i in enumerate(ids) if i]


