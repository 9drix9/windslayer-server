class Spawn:
    """One server-spawned monster placement from a map file's event-2 tile."""
    __slots__ = ('npc', 'x', 'y', 'value', 'tile')

    def __init__(self, npc, x, y, value, tile):
        self.npc, self.x, self.y, self.value, self.tile = npc, x, y, value, tile

    def __repr__(self):
        return f'<Spawn npc={self.npc} at ({self.x:g},{self.y:g}) tile={self.tile} value={self.value}>'


def map_spawns(map_code, indun=False):
    """[Spawn] for the monsters placed on `map_code` (world-template-map, world doc Q7).
    indun=True reads the 2009 instance-dungeon stage `map_code` (indunAA_BB.hmi, S2C 0xA5
    stage codes, en_maps.load_indun) instead of the stage map of that number.

    Source: the EN map file's event-2 tiles whose NpcId template is a monster (type > 2).
    The client ignores exactly those tiles (FUN_00444100) and builds the type <= 2 ones
    (town NPCs) itself, so a town gets no server spawn. The tile's value_num is kept as
    `value` (15 on every map-102 Pupu tile, 30 on most fields, 300 on bosses - it reads
    like a respawn time in seconds, unverified, so the server keeps MOB_RESPAWN_SECS).
    A tile whose NpcId has no hni template is skipped: its 0x1A would bind no template."""
    import en_maps                      # late: en_maps imports this module
    map_code = int(map_code)
    key = ('indun', map_code) if indun else map_code
    with _lock:
        cached = _spawns.get(key)
        if cached is not None:
            return cached
    data = en_maps.load_indun(map_code) if indun else en_maps.load_map(map_code)
    catalog = npcs()
    out = []
    for tile in (data.npc_tiles() if data is not None else []):
        tpl = catalog.get(tile.npc_id)
        if tpl is None:
            log.warning(f'[CONTENT] map {map_code} tile ({tile.x},{tile.y}) NpcId {tile.npc_id}: '
                        f'no hni template - not spawned')
            continue
        if not tpl.is_monster:
            continue
        x, y = data.spawn_point(tile)
        out.append(Spawn(tile.npc_id, x, y, tile.value, (tile.x, tile.y)))
    with _lock:
        _spawns[key] = out
    return out


