class NpcTemplate:
    """One hs/windslayer.hni record: the client's own NPC/monster template (the list at
    game_state+0x4E0 that S2C 0x1A template_index points into)."""
    __slots__ = ('idx', 'position', 'title_text', 'name', 'hsi', 'ai', 'drops', 'shop_items',
                 'quest', 'ui', 'illust', 'lv', 'type', 'hp', 'mp', 'body_atk', 'defense',
                 'weak_atk', 'strong_atk', 'atk_type', 'speed', 'exp', 'attri_atk', 'attri_def')

    def __init__(self, idx, position, title_text, hsi, fields, names):
        f = fields
        self.idx = idx
        self.position = position        # 1-based place in the file = the client list index
        self.title_text = title_text
        self.name = names.get(title_text) or f'npc {idx}'
        self.hsi = hsi
        # `AI:` - 13 ints in 2009, 10 in 2008 (FUN_00409150 -> template+0x254 [+0x250], copied
        # onto the entity by the 0x1A handler: 13 dwords to +0xE50 @0x456C99 [10 to +0xDC0
        # @0x451F67]). The flags the server AI reads are mobai.Flags.of(ai).
        self.ai = _ints(f.get('AI', []))
        ids = _digit_groups(f.get('item', []), NPC_ITEM_SLOTS, 4)
        rates = _digit_groups(f.get('Drop', []), NPC_DROP_SLOTS, 6)
        # (item id, rate) per filled item slot. The rate column is the client's own number;
        # its unit is not verified (per-million reads right: the Pupu card 2030 is 50).
        self.drops = [(i, rates[n]) for n, i in enumerate(ids) if i]
        # The same `item:` column read as a merchant's stock (shop_storage-en-content): the
        # client's shop listing FUN_00465a80 walks record+0x278 (2009 +0x288) up to the FIRST
        # zero id, 0x78 entries at most, so a hole ends the list.
        stock = []
        for i in ids:
            if not i:
                break
            stock.append(i)
        self.shop_items = stock
        self.quest = _int(f.get('Quest'))
        self.ui = _int(f.get('UI'))
        self.illust = _int(f.get('Illust'))
        self.lv = _int(f.get('Lv'))
        self.type = _int(f.get('type'))
        self.hp = _int(f.get('HP'))
        self.mp = _int(f.get('MP'))
        # The 0x1A handler copies these onto the entity (0x456B9E..0x456C10): Body_Atk +0x123C,
        # Weak_Atk +0x11D4, Strong_Atk +0x11D0, Def +0x11E0. The client's own damage estimate
        # (table 0x41A954) hits with Body_Atk for events 1/6, Weak_Atk for 7, Strong_Atk 4/9.
        self.body_atk = _int(f.get('Body_Atk'))
        self.defense = _int(f.get('Def'))
        self.weak_atk = _int(f.get('Weak_Atk'))
        self.strong_atk = _int(f.get('Strong_Atk'))
        self.atk_type = _int(f.get('AtkType'))
        self.speed = _int(f.get('speed'))           # the client stores speed * 0.0001
        self.exp = _int(f.get('Exp'))
        # The element of a type 4..7 template (type - 3: 1 Fire, 2 Ice, 3 Earth, 4 Wind; table
        # 0x41D064): its element attack and the resist of that element (FUN_0041b830
        # [FUN_0041ace0] copies them to +0x11F4 / +0x1200.. [+0x1154 / +0x1160..]; damage.py).
        self.attri_atk = _int(f.get('Attri_Atk'))
        self.attri_def = _int(f.get('Attri_Def'))

    @property
    def is_monster(self):
        """A template the server spawns (FUN_00444100 leaves type > 2 to the server)."""
        return self.type > NPC_CLIENT_SPAWNED_MAX_TYPE

    @property
    def drop_ids(self):
        return [i for i, _ in self.drops]

    @property
    def is_merchant(self):
        """An NPC whose click opens the shop window 0xD (hni `UI: 13`)."""
        return self.ui == UI_NPC_SHOP

    def __repr__(self):
        return f'<NpcTemplate {self.idx} {self.name!r} type={self.type} lv={self.lv} hp={self.hp}>'


class NpcCatalog:
    """hs/windslayer.hni: 180 templates, appended to the client list in file order
    (FUN_00409610 -> CPList::AddTail), so the S2C 0x1A template_index of a record is its
    1-based position in the file. The EN file numbers its records 1..180 in order, so the
    position equals the record idx (= the npccode quests use, hqi NPC/SNPC/ENPC), which
    live test world_movement_npc#21 confirms: templates 2, 3, 4, 6 showed Blue Pupu,
    Well-done Pupu, Blood Pupu and Kamikaze Rat on maps 101 and 102."""

    def __init__(self, defs, source):
        self.defs = defs                                   # idx -> NpcTemplate
        self.source = source
        self._by_position = {d.position: d for d in defs.values()}
        self._first_by_ui = {}                             # ui -> NpcTemplate | None (first_with_ui)

    @classmethod
    def load(cls, path, names):
        text = decode_hs_text(path)
        defs, position = {}, 0
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith('Number_of_'):
                continue
            head, fields = _split_record(line, 4)
            try:
                idx, title = int(head[0], 10), int(head[1], 10)
            except (IndexError, ValueError):
                continue
            position += 1
            defs[idx] = NpcTemplate(idx, position, title, head[2] if len(head) > 2 else '', fields, names)
        if not defs:
            raise ContentError(f'{path}: no NPC records')
        return cls(defs, path)

    def get(self, idx):
        try:
            return self.defs.get(int(idx))
        except (TypeError, ValueError):
            return None

    def template_index(self, idx):
        """The S2C 0x1A template_index for npc idx, or None when the client has no such
        template: an unbound index leaves the entity's +0x11DC NULL (no body, no name,
        nameplate NULL-deref risk at 0x43C4C2), so the caller must not spawn it."""
        d = self.get(idx)
        return None if d is None else d.position

    def at_index(self, template_index):
        return self._by_position.get(template_index)

    def monsters(self):
        return [d for d in self.defs.values() if d.is_monster]

    def merchants(self):
        """The UI-13 templates (56 in both EN builds; idx 7 Smith and 20 "-------" have an
        empty stock)."""
        return [d for d in self.defs.values() if d.is_merchant]

    def shop_list(self, idx):
        """The stock of merchant `idx` (the `npc_id` of C2S 0x0B, window 0xD +0x11C = the
        clicked NPC's hni idx), or None when `idx` is not a merchant. Replaces the KR
        gamedef `npcs.item` / `items.Buy` the old buy handler never even consulted (B4)."""
        d = self.get(idx)
        return list(d.shop_items) if d is not None and d.is_merchant else None

    def first_with_ui(self, ui):
        """The first template (file order) whose `UI:` is `ui`, or None. Cached per catalog, so
        a reload() (a new catalog) starts over."""
        ui = int(ui)
        if ui not in self._first_by_ui:
            self._first_by_ui[ui] = next((d for d in sorted(self.defs.values(), key=lambda t: t.position)
                                          if d.ui == ui), None)
        return self._first_by_ui[ui]

    def __len__(self):
        return len(self.defs)

    def __contains__(self, idx):
        return self.get(idx) is not None


def read_lng(path):
    """{text id: text} from a plaintext hs/*LngKo.lng table (`<id> <text>`, '#' = space)."""
    out = {}
    with open(path, 'rb') as f:
        text = f.read().decode('cp949', 'replace')
    for line in text.splitlines():
        head, _, rest = line.partition(' ')
        if head.isdigit():
            out[int(head)] = rest.replace('#', ' ').strip()
    return out


